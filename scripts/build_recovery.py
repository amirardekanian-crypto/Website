"""Build the recovery rules the two apps read, from recovery/*.toml (2026-11-24, round 14 'The Changeover').

    python scripts/build_recovery.py            write assets/js/recovery.js and scripts/i18n/fa/29-recovery.json
    python scripts/build_recovery.py --check    fail if either is not what the toml files make (check_recovery.py runs this)

recovery/footprint.toml, last-word.toml and matched-pair.toml are the files Amir edits. program.html and coach.html read
them as window.AAREC from assets/js/recovery.js (English only, so the apps stay written in English); the Farsi of every
line goes into the app's word lists as one more part (scripts/i18n/fa/29-recovery.json), which assets/js/i18n.js swaps in
on a Farsi phone like any other text. After a build that changed either file: node scripts/build_i18n_fa.js, then bump
?v= on recovery.js in program.html, coach.html and sw.js's SHELL, the i18n-fa ?v= where it changed, and the CACHE
(recovery/PROCEDURES.md). Run scripts/check_recovery.py before committing; it refuses a file this script would build badly.
"""
import json
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "recovery"
OUT_JS = ROOT / "assets" / "js" / "recovery.js"
OUT_FA = ROOT / "scripts" / "i18n" / "fa" / "29-recovery.json"
TAIL_PATTERNS = [
    [r"(\d+) min, no kit", "{n1} دقیقه، بدون وسیله"],
    [r"(\d+) min, (.+), ticks (.+)", "{n1} دقیقه، {t2}، عادت «{t3}» رو تیک می‌زنه"],
    [r"(\d+) min, (.+)", "{n1} دقیقه، {t2}"],
]


def load():
    return {name: tomllib.loads((SRC / f"{name}.toml").read_text(encoding="utf-8"))
            for name in ("footprint", "last-word", "matched-pair")}


def rules(t):
    """The object the apps read: every number and every English word, nothing else."""
    fp, lw, mp = t["footprint"], t["last-word"], t["matched-pair"]
    art = lw.get("article", {})
    d2 = mp.get("day_two", {})
    return {
        "v": [fp["version"], lw["version"], mp["version"]],
        "fp": {k: fp[k] for k in ("big", "easy", "lower", "sets", "late", "evening", "new", "court")},
        "lw": {
            "label": lw["label"]["en"],
            "lines": [{"id": x["id"], "slot": x["slot"], "when": x["when"], "en": x["en"]} for x in lw["line"]],
            "article": {
                "kick": art.get("kick_en", ""),
                "rules": [{"when": r["when"], "articles": r["articles"]} for r in art.get("rule", [])],
                "say": {s["slug"]: s["en"] for s in art.get("say", [])},
            },
            "b2b": {"en": lw["back_to_back"]["en"], "sessions": lw["back_to_back"]["sessions"]},
            "match": {"en": lw["after_match"]["en"], "sessions": lw["after_match"]["sessions"]},
        },
        "mp": {
            "never": mp["never"],
            "fallback": mp["fallback"],
            "picks": [{"id": p["id"], "areas": p["areas"], "evening": p["evening"], "morning": p["morning"], "kick": p["kick_en"]}
                      for p in mp["pick"]],
            "late": {"sessions": mp["late"]["sessions"], "kick": mp["late"]["kick_en"]},
            "dayTwo": {
                "big": d2.get("big_en", ""), "new": d2.get("new_en", ""),
                "hard": d2.get("hard_en", ""), "hardS": d2.get("hard", []),
                "match": d2.get("match_en", ""), "matchS": d2.get("match", []),
                "two": d2.get("two_en", ""), "twoS": d2.get("two", []),
            },
            "say": {s["session"]: s["en"] for s in mp.get("say", [])},
        },
    }


def farsi(t):
    """English as the app draws it -> its Farsi, for the word lists."""
    lw, mp = t["last-word"], t["matched-pair"]
    pairs = [(lw["label"]["en"], lw["label"]["fa"])]
    pairs += [(x["en"], x["fa"]) for x in lw["line"]]
    art = lw.get("article", {})
    if art.get("kick_en"):
        pairs.append((art["kick_en"], art["kick_fa"]))
    pairs += [(s["en"], s["fa"]) for s in art.get("say", [])]
    pairs += [(lw["back_to_back"]["en"], lw["back_to_back"]["fa"]), (lw["after_match"]["en"], lw["after_match"]["fa"])]
    pairs += [(p["kick_en"], p["kick_fa"]) for p in mp["pick"]]
    pairs.append((mp["late"]["kick_en"], mp["late"]["kick_fa"]))
    d2 = mp.get("day_two", {})
    for k in ("big", "new", "hard", "match", "two"):
        if d2.get(k + "_en"):
            pairs.append((d2[k + "_en"], d2[k + "_fa"]))
    pairs += [(s["en"], s["fa"]) for s in mp.get("say", [])]
    return pairs


def build(t):
    js = ("/* GENERATED by scripts/build_recovery.py from recovery/*.toml. Never hand-edit: change a toml file and rebuild.\n"
          "   The recovery rules program.html and coach.html read (round 14 'The Changeover', 2026-11-24): Footprint's thresholds\n"
          "   (#139), The Last Word's lines (#140), Matched Pair's map (#143), Day Two's and Back-to-Back's words (#141, #142).\n"
          "   English only: the Farsi of every line is in scripts/i18n/fa/29-recovery.json. */\n"
          "window.AAREC = " + json.dumps(rules(t), ensure_ascii=False, indent=1) + ";\n")
    exact = {}
    for en, fa in farsi(t):
        exact[en] = fa
    part = {
        "area": ("GENERATED by scripts/build_recovery.py from recovery/*.toml: edit the toml files, never this part. The recovery "
                 "lines of round 14 'The Changeover' (2026-11-24): The Last Word on the finished card (#140), Matched Pair's rows "
                 "(#143), Day Two on Home (#141) and Back-to-Back in Court Log (#142). Formal (شما). Drafts until Amir has read them."),
        "exact": exact,
        # The tail of a recovery row ("20 min, foam roller, ticks Mobility"), read off the session: the shapes the older Library
        # rows never drew. "17 min, no kit, ticks Mobility" and "6 min read" are already in the lists.
        "patterns": TAIL_PATTERNS,
    }
    fa = json.dumps(part, ensure_ascii=False, indent=2) + "\n"
    return js, fa


def main():
    js, fa = build(load())
    if "--check" in sys.argv:
        stale = []
        for path, want in ((OUT_JS, js), (OUT_FA, fa)):
            have = path.read_text(encoding="utf-8").replace("\r\n", "\n") if path.exists() else ""
            if have != want:
                stale.append(str(path.relative_to(ROOT)))
        if stale:
            print("x stale: " + ", ".join(stale) + ". Run: python scripts/build_recovery.py")
            return 1
        print("ok  assets/js/recovery.js and 29-recovery.json match recovery/*.toml")
        return 0
    OUT_JS.write_text(js, encoding="utf-8", newline="\n")
    OUT_FA.write_text(fa, encoding="utf-8", newline="\n")
    print(f"ok  wrote {OUT_JS.relative_to(ROOT)} and {OUT_FA.relative_to(ROOT)}")
    print("    next: node scripts/build_i18n_fa.js, then the ?v= bumps and the CACHE (recovery/PROCEDURES.md)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
