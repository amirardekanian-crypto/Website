// Builds /assets/js/i18n-fa.js, the Farsi words of the athlete app, from scripts/i18n/fa/*.json (2026-11-20).
//
//   node scripts/build_i18n_fa.js            build it
//   node scripts/build_i18n_fa.js --check    fail if the built file is not what the parts make (pre-commit can run this)
//
// Each part is { "area": "...", "exact": { "English as drawn": "Farsi" }, "patterns": [["regex source", "template"]] }.
// Parts are read in file-name order and a later part wins a clash (00-core.json is the glossary, so it goes first and
// any area that disagrees with it is reported). The engine and the template grammar are in assets/js/i18n.js.
// After a rebuild, bump ?v= on data-fa in program.html, the same URL in sw.js's SHELL, and the CACHE.
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
const DIR = path.join(__dirname, 'i18n', 'fa');
const OUT = path.join(ROOT, 'assets', 'js', 'i18n-fa.js');
const norm = s => String(s).replace(/[‘’]/g, "'").replace(/[“”]/g, '"').replace(/\s+/g, ' ').trim();

const exact = {}, from = {}, patterns = [], seenPat = new Set(), notes = [];
let bad = 0;
for (const f of fs.readdirSync(DIR).filter(f => f.endsWith('.json')).sort()) {
  let part;
  try { part = JSON.parse(fs.readFileSync(path.join(DIR, f), 'utf8')); }
  catch (e) { console.error(`✗ ${f}: not JSON (${e.message})`); bad++; continue; }
  for (const [en0, fa] of Object.entries(part.exact || {})) {
    const en = norm(en0);
    if (!en || typeof fa !== 'string' || !fa.trim()) continue;
    if (exact[en] != null && exact[en] !== fa) notes.push(`${f} changes "${en}" (was ${from[en]}'s)`);
    exact[en] = fa; from[en] = f;
  }
  for (const p of part.patterns || []) {
    if (!Array.isArray(p) || typeof p[0] !== 'string' || typeof p[1] !== 'string') { console.error(`✗ ${f}: a pattern is not [source, template]: ${JSON.stringify(p)}`); bad++; continue; }
    try { new RegExp('^' + p[0] + '$'); } catch (e) { console.error(`✗ ${f}: bad regex ${p[0]} (${e.message})`); bad++; continue; }
    if (seenPat.has(p[0])) continue;
    seenPat.add(p[0]); patterns.push([p[0], p[1]]);
  }
}
// The narrowest pattern first: a longer literal part wins over a looser one that would also match.
const lit = s => s.replace(/\\.|\[[^\]]*\]|\([^)]*\)|[.*+?{}|^$]/g, '').length;
patterns.sort((a, b) => lit(b[0]) - lit(a[0]));

const body = `/* GENERATED by scripts/build_i18n_fa.js from scripts/i18n/fa/*.json. Never hand-edit: change a part and rebuild.
   The athlete app's words in Farsi (assets/js/i18n.js reads them). ${Object.keys(exact).length} strings, ${patterns.length} patterns. */
AAI18N.addFa(${JSON.stringify(exact, null, 0).replace(/","/g, '",\n"')},
${JSON.stringify(patterns).replace(/\],\[/g, '],\n[')});
`;
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
  if (cur !== body || bad) { console.error('✗ assets/js/i18n-fa.js is stale or a part is broken: node scripts/build_i18n_fa.js'); process.exit(1); }
  console.log('✓ i18n-fa.js matches its parts'); process.exit(0);
}
if (bad) process.exit(1);
fs.writeFileSync(OUT, body);
notes.forEach(n => console.log('· ' + n));
console.log(`✓ ${path.relative(ROOT, OUT)}: ${Object.keys(exact).length} strings, ${patterns.length} patterns`);
