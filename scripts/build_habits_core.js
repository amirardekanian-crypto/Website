/* ═══════════════════════════════════════════════════════════════════════════
   build_habits_core.js — cut the habit engine out of habits.html and write it
   to assets/js/habits-core.js, the ONE copy both apps read.

       node scripts/build_habits_core.js            write it
       node scripts/build_habits_core.js --check    fail if it is stale (the hook)

   WHY A GENERATOR. AA Proof is being retired into program.html (2026-10-19,
   Amir: "Aa proof will die"), and program.html has to own the habits: the
   roster, the log, the verdict, the day streak, the backfill. Retyping that
   engine into a second file is exactly the failure this repo has a guard for —
   "things that exist more than once: change every copy", and when the two
   copies drift NOTHING ERRORS, the athlete and the board simply disagree.
   So nothing is retyped. Each function is cut from habits.html BY NAME, byte
   for byte, and assembled into one file. While AA Proof is still alive,
   habits.html stays the source of truth and this file follows it.

   WHEN PROOF DIES: habits-core.js becomes the source of truth. Delete this
   script and guard 26 in .githooks/pre-commit, and the file stands on its own.

   WHAT IS NOT IN IT. The XP ladder, the badges, the quests and the board stay
   where they are: the career's numbers come from the server (get_profile), and
   program.html already draws them. This is only what the app needs to SHOW and
   LOG a day — scoring a day's weight is in it only because the verdict and the
   day streak are computed from it.
   ═══════════════════════════════════════════════════════════════════════════ */
'use strict';
const fs = require('fs'), path = require('path'), vm = require('vm');
const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'habits.html');
const OUT = path.join(ROOT, 'assets', 'js', 'habits-core.js');

function bail(msg) { console.error('build_habits_core: ' + msg); process.exit(1); }

// Cut `function name(...) { ... }` whole, by compiling candidates until one parses.
function fnSrc(src, name) {
  const m = new RegExp('^function ' + name + '\\(', 'm').exec(src);
  if (!m) bail('habits.html: could not find function ' + name + '(). Renamed or moved? Update this script.');
  const eol = src.indexOf('\n', m.index);
  const first = src.slice(m.index, eol < 0 ? src.length : eol);
  try { new vm.Script(first); return first; } catch (e) { /* a multi-line function */ }
  let end = m.index;
  for (;;) {
    end = src.indexOf('\n}', end + 1);
    if (end < 0) bail('habits.html: function ' + name + '() never closes');
    const code = src.slice(m.index, end + 2);
    try { new vm.Script(code); return code; } catch (e) { /* keep looking */ }
  }
}
// Cut `const NAME = …;` whole, however many lines it runs to.
function constSrc(src, name) {
  const i = src.indexOf('\nconst ' + name + ' = ');
  if (i < 0) bail('habits.html: could not find const ' + name + '. Update this script.');
  let end = i + 1;
  for (;;) {
    end = src.indexOf(';\n', end + 1);
    if (end < 0) bail('habits.html: const ' + name + ' never ends');
    const code = src.slice(i + 1, end + 1);
    try { new vm.Script(code); return code; } catch (e) { /* keep looking */ }
  }
}
function lineSrc(src, start) {
  const i = src.indexOf('\n' + start);
  if (i < 0) bail('habits.html: could not find the line starting "' + start + '". Update this script.');
  const j = src.indexOf('\n', i + 1);
  return src.slice(i + 1, j);
}

// Everything the engine is made of, in the order it must be declared.
const CONSTS = ['XP_RULES', 'HABITS', 'HABIT_HUES'];
const LINES = ['const MAX_CUSTOM =', 'const BACKFILL_DAYS =', 'const TKEY =', 'const AKEY ='];
const FNS = [
  // dates and the backfill window
  'today', 'addDays', 'fmtKey', 'parseKey', 'oldestLoggable', 'canLog', 'editingPast', 'dayShort', 'dayLong',
  // the catalogue
  'customCount', 'customRoom', 'habitHue', 'splitEmoji', 'allHabits', 'habitById', 'shortName',
  'live', 'offHabits', 'addOnHabits', 'lockedOnToday',
  // the roster timeline
  'firstLoggedDay', 'rosterHabits', 'rosterOn', 'rosterAt', 'sameIds', 'rosterPut', 'rosterDrop',
  'anchorRoster', 'stampRoster',
  // the log
  'valOf', 'isDone', 'fmtVal',
  // what a day is worth, and whether it counts
  'baseXp', 'dayParts', 'dayPct', 'gatePct', 'isPerfect', 'gatePasses', 'dayQualifies',
  'lackOf', 'dayToGo', 'verdictOf', 'dayStreakAt', 'currentDayStreak',
  // the config
  'defaultCfg',
];

const HEAD = `/* ═══════════════════════════════════════════════════════════════════════════
   habits-core.js — THE HABIT ENGINE. One copy, read by program.html.

   ⚠️ GENERATED. Do not edit this file by hand: every line of it is cut out of
   habits.html, by name, by scripts/build_habits_core.js, and guard 26 in
   .githooks/pre-commit fails the commit if the two have drifted. Change the
   behaviour in habits.html and run the generator.

   AA Proof is being retired into the training app (2026-10-19). program.html
   has to own the habits now — the roster, the log, the verdict, the day streak,
   the backfill — and a retyped second copy of this is how the athlete and the
   board end up disagreeing with nothing to show for it. So nothing here is
   retyped.

   WHAT IT NEEDS from the page that loads it, as globals:
     CFG   the athlete's habit config  (<id>_hab_cfg), defaultCfg() shaped
     LOG   the athlete's habit log     (<id>_hab_log), { 'YYYY-MM-DD': { id: n } }
     UI    an object with a \`day\` field: the day being filled in, null for today
   It reads them and never writes them: saving, syncing and drawing belong to
   the app. AA Proof's own copies of these names are the same objects.

   WHAT IT IS NOT. No XP ladder, no badges, no quests, no board: the career's
   numbers are the server's (get_profile) and program.html already draws them.
   A day's weight is in here only because the verdict and the day streak are
   computed from it.
   ═══════════════════════════════════════════════════════════════════════════ */
(function (root) {
  'use strict';
  // The page's own state. Set by habitsCoreBind() before anything else is called.
  let CFG = null, LOG = {}, UI = { day: null };

`;

const FOOT = `
  // ── The one way in ──────────────────────────────────────────────────────
  // The app hands over its three objects; everything above reads them live, so a
  // later CFG or LOG replacement (a cloud merge, a sign-out) only needs binding again.
  function habitsCoreBind(cfg, log, ui) {
    CFG = cfg; LOG = log; UI = ui || { day: null };
    _rosterCache = null;
  }

  root.AAHabits = {
    bind: habitsCoreBind,
    // the catalogue
    HABITS: HABITS, XP_RULES: XP_RULES, MAX_CUSTOM: MAX_CUSTOM, BACKFILL_DAYS: BACKFILL_DAYS,
    all: allHabits, byId: habitById, live: live, addOns: addOnHabits, off: offHabits,
    shortName: shortName, splitEmoji: splitEmoji, hue: habitHue, lockedOnToday: lockedOnToday,
    customCount: customCount, customRoom: customRoom,
    // dates and the window
    today: today, addDays: addDays, fmtKey: fmtKey, parseKey: parseKey, TKEY: TKEY, AKEY: AKEY,
    canLog: canLog, oldestLoggable: oldestLoggable, editingPast: editingPast,
    dayShort: dayShort, dayLong: dayLong,
    // the log
    valOf: valOf, isDone: isDone, fmtVal: fmtVal, firstLoggedDay: firstLoggedDay,
    // the roster timeline
    rosterOn: rosterOn, stampRoster: stampRoster, anchorRoster: anchorRoster,
    // the day
    dayParts: dayParts, dayPct: dayPct, isPerfect: isPerfect, dayQualifies: dayQualifies,
    dayToGo: dayToGo, verdict: verdictOf, dayStreakAt: dayStreakAt, dayStreak: currentDayStreak,
    // the config
    defaultCfg: defaultCfg,
  };
})(typeof window !== 'undefined' ? window : globalThis);
`;

function build() {
  // LF, always: the tree is CRLF, and every cut below looks for "\n}" or ";\n".
  const src = fs.readFileSync(SRC, 'utf8').replace(/\r\n/g, '\n');
  const parts = [];
  CONSTS.forEach(n => parts.push(constSrc(src, n)));
  LINES.forEach(l => parts.push(lineSrc(src, l)));
  FNS.forEach(n => parts.push(fnSrc(src, n)));
  // Indented two spaces, so the whole engine sits inside the module's closure.
  const body = parts.join('\n\n').split('\n').map(l => (l.trim() ? '  ' + l : l)).join('\n');
  // _rosterCache is habits.html's module-level cache; it is declared with the functions there.
  const text = HEAD + '  let _rosterCache = null;\n\n' + body + '\n' + FOOT;
  // It must at least parse, and the names the app calls must all be there.
  try { new vm.Script(text); } catch (e) { bail('the assembled file does not parse: ' + e.message); }
  return text.replace(/\r\n/g, '\n');
}

const text = build();
const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : null;

if (process.argv.indexOf('--check') >= 0) {
  if (have === text) { console.log('habits-core: OK (in step with habits.html)'); process.exit(0); }
  console.error('habits-core: STALE — habits.html has moved and assets/js/habits-core.js has not.');
  console.error('Run: node scripts/build_habits_core.js   then stage assets/js/habits-core.js');
  process.exit(1);
}

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, text);
console.log('habits-core: written, ' + text.split('\n').length + ' lines, ' +
  (CONSTS.length + LINES.length + FNS.length) + ' pieces cut from habits.html');
