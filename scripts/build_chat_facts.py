"""Builds the website chatbot's knowledge from Content/CHATBOT-FACTS.md.

The facts file is the one thing the chatbot knows (supabase/functions/site-chat). Its sections are
marked [both], [en] or [fa]; this script writes supabase/functions/site-chat/facts.ts with one text
per site: [both] + [en] for the English site, [both] + [fa] for the Farsi site. Everything above the
first marked section is a note to Amir and never reaches the bot.

    python scripts/build_chat_facts.py           write facts.ts
    python scripts/build_chat_facts.py --check   fail when facts.ts is not what the facts file makes (pre-commit)

After writing, redeploy site-chat with the Supabase tool (supabase/functions/README.md).
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'Content', 'CHATBOT-FACTS.md')
OUT = os.path.join(ROOT, 'supabase', 'functions', 'site-chat', 'facts.ts')


def build():
    text = open(SRC, encoding='utf-8').read().replace('\r\n', '\n')
    parts = re.split(r'^## \[(both|en|fa)\] ', text, flags=re.M)
    if len(parts) < 3:
        sys.exit('build_chat_facts: no "## [both|en|fa]" sections in ' + SRC)
    by = {'both': [], 'en': [], 'fa': []}
    for tag, body in zip(parts[1::2], parts[2::2]):
        body = re.sub(r'\n-{3,}\n', '\n', body).strip()
        by[tag].append('## ' + body)
    site = {s: '\n\n'.join(by['both'] + by[s]) for s in ('en', 'fa')}
    lines = [
        '// GENERATED by scripts/build_chat_facts.py from Content/CHATBOT-FACTS.md. Do not edit: edit the facts file and rebuild.',
        'export const FACTS: Record<"en" | "fa", string> = {',
    ]
    for s in ('en', 'fa'):
        lines.append(f'  {s}: {json.dumps(site[s], ensure_ascii=False)},')
    lines.append('};')
    return '\n'.join(lines) + '\n'


def main():
    want = build()
    if '--check' in sys.argv:
        have = open(OUT, encoding='utf-8').read().replace('\r\n', '\n') if os.path.exists(OUT) else ''
        if have != want:
            sys.exit('site-chat/facts.ts is stale: run  python scripts/build_chat_facts.py  and redeploy site-chat.')
        print('chat facts: up to date')
        return
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(want)
    print('wrote', os.path.relpath(OUT, ROOT), f'({len(want)} chars). Redeploy site-chat.')


if __name__ == '__main__':
    main()
