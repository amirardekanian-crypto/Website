#!/usr/bin/env python
"""Turn scripts/restore/catalog.sql's answer into supabase/schema_snapshot.sql: the whole `public` schema as SQL, for a FRESH database.

    python scripts/restore/make_schema_snapshot.py <catalog-answer> [--out supabase/schema_snapshot.sql] [--date 2026-10-11]

<catalog-answer> is either the file the Supabase tool saved when scripts/restore/catalog.sql was run (it says "Output has been saved to <path>"), or a
plain JSON file holding the catalog document. Nothing is read from a database here.

What it writes, in the order a fresh database needs it:
  1. sequences   (the ones behind a serial-style default; an identity column makes its own)
  2. tables      (columns, defaults, identity, generated columns; no constraints yet, so a table may come in any order)
  3. functions   (after the tables: a few return a table's row type, like SETOF messages. check_function_bodies is off, so a SQL function's body may
                  name anything. Before the constraints: two CHECKs call spine_credits_ok())
  4. constraints (primary keys, unique keys and checks first, foreign keys last, so no table has to come before another)
  5. indexes     (the ones no constraint made), triggers, row-level security, policies
  6. grants      (exact: every role's table and function privileges, as the live project has them)
  7. the trigger on auth.users that calls a public function (stage51); the rest of the auth schema is Supabase's own
It refuses anything it does not know how to write (a view, a custom type, an aggregate, a constraint kind it has never seen), and says so, so a
new kind of object can never go missing from the snapshot without anyone noticing.
"""
import argparse, datetime, json, re, sys

ROLES = ['anon', 'authenticated', 'service_role']          # the roles Supabase itself provides; the owner (postgres) needs no grant
CMD = {'*': 'ALL', 'r': 'SELECT', 'a': 'INSERT', 'w': 'UPDATE', 'd': 'DELETE'}


def load(path):
    raw = open(path, encoding='utf-8').read()
    doc = json.loads(raw)
    if isinstance(doc, dict) and 'tables' in doc:
        return doc                                           # a plain catalog document
    s = doc['result'] if isinstance(doc, dict) and 'result' in doc else raw   # the Supabase tool's saved answer
    a = s.index('[', s.index('<untrusted-data'))
    b = s.rindex(']', 0, s.rindex('</untrusted-data'))
    rows = json.loads(s[a:b + 1])
    return rows[0]['catalog']


def q(name):
    return '"' + str(name).replace('"', '""') + '"'


def ident(name):
    return name if re.fullmatch(r'[a-z_][a-z0-9_]*', name) else q(name)


def lit(s):
    return "'" + str(s).replace("'", "''") + "'"


def priv_list(grants, grantee):
    order = ['SELECT', 'INSERT', 'UPDATE', 'DELETE', 'TRUNCATE', 'REFERENCES', 'TRIGGER']
    got = [g['priv'] for g in grants if g['grantee'] == grantee]
    return [p for p in order if p in got] + sorted(p for p in got if p not in order)


def column_sql(c, table):
    out = [ident(c['name']), c['type']]
    if c.get('collation'):
        out.append('collate ' + q(c['collation']))
    if c.get('generated') == 's':
        out.append('generated always as (' + c['default'] + ') stored')
    elif c.get('identity') in ('a', 'd'):
        out.append('generated ' + ('always' if c['identity'] == 'a' else 'by default') + ' as identity')
    elif c.get('default') is not None:
        out.append('default ' + c['default'])
    if c['notnull']:
        out.append('not null')
    return ' '.join(out)


def build(cat, date):
    problems = []
    for key in ('types', 'views', 'other_routines'):
        if cat.get(key):
            problems.append(f'the catalog has {key}: {cat[key]!r}. This script does not write them yet: teach it first.')
    tables, funcs = cat['tables'], cat['functions']

    out = []
    add = out.append
    add(f"""-- supabase/schema_snapshot.sql: the `public` schema of Supabase project bvipfipbdcyqnbczjmaq as it stood on {date} (PostgreSQL {cat['generated_from']['server_version']}).
-- GENERATED by scripts/restore/make_schema_snapshot.py from the answer to scripts/restore/catalog.sql. Do not edit it by hand: run those two again.
--
-- For a FRESH Supabase project (or a scratch Postgres with scripts/restore/stand_in_supabase.sql applied first). It creates everything and fails
-- loudly on a database that already has these objects, on purpose: running it on a live project would be a mistake, not a repair.
-- It holds the structure only: tables, columns, constraints, indexes, row-level security and its policies, triggers, every function and who may run it,
-- and every grant. The rows come from a backup file (scripts/restore/README.md). Nothing in the `auth`, `storage`, `realtime`, `vault` or `backup`
-- schemas is here: Supabase makes the first four itself, and `backup` held one-off rollback copies, not part of the product.
-- The extensions the live project has: {', '.join(e['name'] + ' (' + e['schema'] + ')' for e in cat['extensions'])}.
-- A new Supabase project already has all of them (plpgsql, pgcrypto, uuid-ossp, pg_stat_statements, supabase_vault).
-- {len(tables)} tables, {len(funcs)} functions, {len(cat['sequences'])} sequences.

set check_function_bodies = off;
set search_path = public;
""")

    # 2. sequences that a serial-style default uses (an identity column creates its own)
    add('-- ── 1. sequences behind a serial-style default ' + '─' * 30)
    owned = []
    for s in cat['sequences']:
        if s['identity']:
            continue
        typ = s['type']
        add(f"create sequence public.{ident(s['name'])} as {typ} start with {s['start']} increment by {s['increment']} cache {s['cache']};")
        if s['owned_by']:
            owned.append(s)
    add('')

    # 3. tables
    add('-- ── 2. tables ' + '─' * 63)
    for t in tables:
        cols = ',\n  '.join(column_sql(c, t['name']) for c in t['columns'])
        add(f"create table public.{ident(t['name'])} (\n  {cols}\n);\n")
    for s in owned:
        tbl, col = s['owned_by'].split('.')
        add(f"alter sequence public.{ident(s['name'])} owned by public.{ident(tbl)}.{ident(col)};")
    add('')

    # 1. functions
    add('-- ── 3. functions ' + '─' * 60)
    for f in funcs:
        d = f['def'].rstrip()
        if not d.startswith('CREATE OR REPLACE FUNCTION'):
            problems.append(f"function {f['name']}: its definition does not start with CREATE OR REPLACE FUNCTION")
        add(d + ';\n')

    # 4. constraints: everything but foreign keys, then the foreign keys
    add('-- ── 4. constraints ' + '─' * 59)
    fks = []
    for t in tables:
        for k in t['constraints']:
            if k['type'] == 'n':
                continue                                     # a NOT NULL kept as a constraint (PostgreSQL 18): the column already says it
            if k['type'] not in ('p', 'u', 'c', 'f'):
                problems.append(f"table {t['name']}: constraint {k['name']} is of kind {k['type']!r}, which this script does not write")
                continue
            stmt = f"alter table public.{ident(t['name'])} add constraint {ident(k['name'])} {k['def']};"
            (fks if k['type'] == 'f' else out).append(stmt)
    add('-- foreign keys, last')
    out.extend(fks)
    add('')

    # 5. indexes, triggers, row-level security, policies
    add('-- ── 5. indexes, triggers, row-level security, policies ' + '─' * 22)
    for t in tables:
        for i in t['indexes']:
            if not i['for_constraint']:
                add(i['def'] + ';')
    add('')
    for t in tables:
        for g in t['triggers']:
            add(g['def'] + ';')
    add('')
    for t in tables:
        if t['rls']:
            add(f"alter table public.{ident(t['name'])} enable row level security;")
        if t['force_rls']:
            add(f"alter table public.{ident(t['name'])} force row level security;")
    add('')
    for t in tables:
        for p in t['policies']:
            roles = ', '.join(('public' if r == 'public' else ident(r)) for r in (p['roles'] or ['public']))
            parts = [f"create policy {q(p['name'])} on public.{ident(t['name'])} as {'permissive' if p['permissive'] else 'restrictive'} for {CMD[p['cmd']]} to {roles}"]
            if p['using'] is not None:
                parts.append(f"using ({p['using']})")
            if p['check'] is not None:
                parts.append(f"with check ({p['check']})")
            add(' '.join(parts) + ';')
    add('')

    # 6. grants
    add('-- ── 6. grants: exactly what the live project has ' + '─' * 28)
    for t in tables:
        tn = f"public.{ident(t['name'])}"
        add(f"revoke all on table {tn} from public, {', '.join(ROLES)};")
        for r in ROLES + ['PUBLIC']:
            privs = priv_list(t['grants'], r)
            if privs:
                add(f"grant {', '.join(p.lower() for p in privs)} on table {tn} to {'public' if r == 'PUBLIC' else r};")
    add('')
    for f in funcs:
        sig = f"public.{ident(f['name'])}({f['args']})"
        add(f"revoke all on function {sig} from public, {', '.join(ROLES)};")
        who = [r for r in ROLES + ['PUBLIC'] if any(g['grantee'] == r and g['priv'] == 'EXECUTE' for g in f['grants'])]
        if who:
            add(f"grant execute on function {sig} to {', '.join('public' if r == 'PUBLIC' else r for r in who)};")
    add('')

    # 7. the trigger the product keeps on Supabase's own sign-in table (it calls a public function, so it comes after the functions)
    add('-- ── 7. the trigger on the sign-in table (auth.users) that calls a public function ' + '─' * 8)
    for g in cat.get('auth_triggers', []):
        add(g['def'] + ';')
    add('')
    add('reset check_function_bodies;')

    # Is anything here that would not run on a fresh database? (a default that calls a public function would need it BEFORE the table: it does, functions are first)
    return '\n'.join(out) + '\n', problems


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('catalog')
    ap.add_argument('--out', default='supabase/schema_snapshot.sql')
    ap.add_argument('--date', default=datetime.date.today().isoformat())
    a = ap.parse_args()
    cat = load(a.catalog)
    sql, problems = build(cat, a.date)
    if problems:
        print('NOT WRITTEN, nothing is left out silently:\n  ' + '\n  '.join(problems), file=sys.stderr)
        sys.exit(1)
    with open(a.out, 'w', encoding='utf-8', newline='\n') as f:
        f.write(sql)
    print(f"wrote {a.out}: {len(cat['tables'])} tables, {len(cat['functions'])} functions, {len(sql):,} characters")


if __name__ == '__main__':
    main()
