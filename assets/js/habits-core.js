    growth: 0.55,           // cost(n) = base × n^growth — higher = steeper climb
    completionBonus: 1.2,   // multiplier once a habit's target is met
    customXp: 25,           // per-completion value of an athlete-added habit
    // A day counts toward the day-streak at this % of the WEIGHT it could earn —
    // see dayParts(). 75, not 80, and the five points are load-bearing: the gate's
    // denominator on a rest day is the seven daily habits (250), so the worst
    // single miss is steps at 190/250 = 76%. At 80 that fails and steps quietly
    // becomes a second precondition alongside the session; at 75 the old promise
    // — "miss any one thing and the day still counts" — survives on every roster
    // on the board.
    //
    // ⚠️ RAISED BACK TO 80 (Amir, 2026-08-02: "I think 75% is very low. Make it
    // 80."). The paragraph above is the reasoning from when this went 80 → 75,
    // and it is now OUT OF DATE in the one way that matters: it predates the
    // GATE'S SECOND DOOR. dayQualifies() no longer asks the percentage alone —
    // `missing <= 1 && done > 0` passes a day that left at most one thing
    // undone, whatever the arithmetic says. So the exact failure this comment
    // was written to prevent (miss steps alone on a rest day and lose the day)
    // cannot happen at 80 either: one miss is one miss, and it goes through the
    // second door. What 80 actually tightens is the day that missed THREE
    // things by a little each — Amir's own Fri 31 Jul, 79% on partial credit
    // for steps, sleep and protein, which is precisely the day he looked at and
    // said the bar was too low. Do not "restore" 75 from the paragraph above
    // without re-reading dayQualifies() first.
